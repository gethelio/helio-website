#!/usr/bin/env node
/**
 * Post-build script to fix Vercel build output issues:
 * 1. Runtime fix: older adapters can emit nodejs18.x → patch those to nodejs20.x
 *    Do not downgrade nodejs22.x (current @astrojs/vercel default).
 * 2. Trailing-slash redirect fix: catch-all routes ([...param]) generate overly broad
 *    regex patterns that match URLs already ending in "/", causing infinite 308 loops.
 */

import fs from 'fs'
import path from 'path'

const OUTPUT_DIR = '.vercel/output'
const FUNCTIONS_DIR = path.join(OUTPUT_DIR, 'functions')
const CONFIG_PATH = path.join(OUTPUT_DIR, 'config.json')
const LEGACY_RUNTIMES = new Set(['nodejs18.x'])
const TARGET_RUNTIME = 'nodejs20.x'

// ── 1. Fix function runtime ────────────────────────────────────────────────

function fixRuntime(dir) {
  if (!fs.existsSync(dir)) {
    console.log('No functions directory found, skipping runtime fix')
    return
  }

  const entries = fs.readdirSync(dir, { withFileTypes: true })
  
  for (const entry of entries) {
    if (entry.isDirectory() && entry.name.endsWith('.func')) {
      const configPath = path.join(dir, entry.name, '.vc-config.json')
      
      if (fs.existsSync(configPath)) {
        const config = JSON.parse(fs.readFileSync(configPath, 'utf-8'))
        
        if (config.runtime && LEGACY_RUNTIMES.has(config.runtime)) {
          console.log(`Fixing runtime in ${entry.name}: ${config.runtime} -> ${TARGET_RUNTIME}`)
          config.runtime = TARGET_RUNTIME
          fs.writeFileSync(configPath, JSON.stringify(config, null, 2))
        }
      }
    }
  }
  
  console.log('Runtime fix complete')
}

// ── 2. Fix trailing-slash redirect loops for catch-all routes ──────────────
//
// The @astrojs/vercel adapter generates redirect rules like:
//   { src: "/blog(?:\\/(.*?))?", headers: { Location: "/blog/$1/" }, status: 308 }
//
// The regex matches "/blog/" (with $1 = ""), producing Location "/blog//" which
// Vercel normalises back to "/blog/" → infinite redirect loop.
//
// Fix: replace each catch-all rule with two precise rules:
//   a) Exact match without slash → add trailing slash  (e.g. /blog → /blog/)
//   b) Sub-path without trailing slash → add it         (e.g. /blog/foo → /blog/foo/)
// This ensures "/blog/" and "/blog/foo/" are NOT matched, so they fall through
// to the filesystem handler and serve the static HTML.

/** Detect the catch-all trailing-slash pattern generated by the adapter */
const CATCHALL_RE = /^(\/[a-z0-9_-]+)\(\?:\\\/\(\.\*\?\)\)\?$/i

function fixTrailingSlashRedirects(configPath) {
  if (!fs.existsSync(configPath)) {
    console.log('No config.json found, skipping redirect fix')
    return
  }

  const config = JSON.parse(fs.readFileSync(configPath, 'utf-8'))
  if (!config.routes) return

  const seen = new Set()
  const newRoutes = []

  for (const route of config.routes) {
    const match = route.src && CATCHALL_RE.exec(route.src)

    if (match && route.status === 308) {
      const base = match[1] // e.g. "/blog"

      // Deduplicate – [...page].astro and [...slug].astro both emit the same rule
      if (seen.has(base)) continue
      seen.add(base)

      // Rule a: exact path without trailing slash → add slash
      newRoutes.push({
        src: base,
        headers: { Location: `${base}/` },
        status: 308,
      })

      // Rule b: sub-path missing trailing slash (e.g. /blog/my-post)
      newRoutes.push({
        src: `${base}/(.+[^/])`,
        headers: { Location: `${base}/$1/` },
        status: 308,
      })

      console.log(`Fixed trailing-slash redirect for ${base}`)
    } else {
      newRoutes.push(route)
    }
  }

  config.routes = newRoutes
  fs.writeFileSync(configPath, JSON.stringify(config, null, '\t'))
  console.log('Trailing-slash redirect fix complete')
}

// ── Run fixes ──────────────────────────────────────────────────────────────

fixRuntime(FUNCTIONS_DIR)
fixTrailingSlashRedirects(CONFIG_PATH)
